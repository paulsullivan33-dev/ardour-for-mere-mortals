local function step(name, fn) local ok, err = pcall(fn); print("STEP " .. name .. " ->", ok, err); return ok end
AudioEngine:set_backend("None (Dummy)", "Dummy", "")
print("backend now:", AudioEngine:current_backend_name())
local sess = load_session("/home/hatch/workspace/ardour-labwork/FirstTake", "FirstTake")
print("session:", sess:name(), "rate:", sess:sample_rate())
local TRS = ARDOUR.TransportRequestSource.TRS_UI
local track
step("add stereo audio track 'Tone'", function()
  local tl = sess:new_audio_track(2, 2, nil, 1, "Tone", -1, ARDOUR.TrackMode.Normal, true)
  track = tl:front():to_track()
  print("  track name:", track:name())
end)
step("add ACE Compressor (a-comp.lv2) to Tone", function()
  local proc = ARDOUR.LuaAPI.new_plugin(sess, "ACE Compressor", ARDOUR.PluginType.LV2, "")
  print("  plugin isnil:", proc:isnil())
  local rv = track:add_processor_by_index(proc, 0, nil, true)
  print("  add_processor_by_index returned:", rv)
  print("  processors on track now:", track:nth_processor(0):display_name())
end)
step("arm track for recording", function()
  track:rec_enable_control():set_value(1, PBD.GroupControlDisposition.NoGroup)
  sess:maybe_enable_record()
end)
step("roll (record)", function() return sess:request_roll(TRS) end)
sleep(4)
print("transport sample after ~4s:", sess:transport_sample(), "speed:", sess:transport_speed())
step("stop, keeping the take", function() return sess:request_stop(false, false, TRS) end)
sleep(1)
step("inspect playlist", function()
  local pl = track:playlist()
  print("  playlist:", pl:name(), "region count:", pl:region_list():size())
  for r in pl:region_list():iter() do
    print("  region:", r:name(), "length(samples):", r:length(), "length(sec):", r:length() / sess:sample_rate(), "position:", r:position())
  end
end)
step("save session", function() return sess:save_state("", false, false, false) end)
step("list routes", function()
  for r in sess:get_routes():iter() do print("  route:", r:name()) end
end)
